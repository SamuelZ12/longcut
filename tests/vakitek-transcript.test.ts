import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { fetchVakitekTranscript, VAKITEK_TIMEOUT_MS } from '@/lib/vakitek-transcript-provider';

const upstream = vi.fn();
const input = { videoId: 'abcdefghijk', apiKey: 'secret-test-key', requestId: 'test-request' };
const nativeBody = {
  data: [{
    videoId: 'abcdefghijk', language: 'es', originalLanguage: 'es', isAutoGenerated: false,
    transcript: [
      { start: 0.18, dur: 3.41, text: 'Early caption.' },
      { start: 8.15, dur: 1.2, text: 'Later caption.' },
    ],
    wordCount: 4, availableLanguages: ['es'],
  }],
  meta: {}, billing: { events: { transcript: 1 } },
};

beforeEach(() => {
  vi.clearAllMocks();
  vi.stubGlobal('fetch', upstream);
  vi.spyOn(console, 'info').mockImplementation(() => {});
});
afterEach(() => { vi.unstubAllGlobals(); vi.useRealTimers(); });

function expectOneNativeCall() {
  expect(upstream).toHaveBeenCalledTimes(1);
  expect(new URL(upstream.mock.calls[0][0]).searchParams.get('video')).toBe(input.videoId);
  expect(new URL(upstream.mock.calls[0][0]).searchParams.get('format')).toBe('json');
}

function completion() {
  return vi.mocked(console.info).mock.calls.map(([line]) => JSON.parse(String(line)))
    .find(event => event.event === 'vakitek_transcript_completed');
}

it('fetches native captions once and keeps the documented second units', async () => {
  upstream.mockResolvedValue(Response.json(nativeBody));
  const result = await fetchVakitekTranscript({ ...input, lang: 'en' });
  expect(result).toMatchObject({
    outcome: 'success', language: 'es', availableLanguages: ['es'],
    segments: [
      { text: 'Early caption.', start: 0.18, duration: 3.41 },
      { text: 'Later caption.', start: 8.15, duration: 1.2 },
    ],
    metadata: { source: 'vakitek', mode: 'native', upstreamStatus: 200, billableCredits: 1, billingKind: 'reported', requestId: 'test-request' },
  });
  expectOneNativeCall();
  const [url, options] = upstream.mock.calls[0];
  expect(new URL(url).searchParams.get('target_language')).toBe('en');
  expect(options).toMatchObject({ redirect: 'error', cache: 'no-store', headers: { 'X-API-Key': 'secret-test-key' } });
});

it('omits target_language when no language is requested', async () => {
  upstream.mockResolvedValue(Response.json(nativeBody));
  await fetchVakitekTranscript(input);
  expect(new URL(upstream.mock.calls[0][0]).searchParams.has('target_language')).toBe(false);
});

it.each([
  ['NO_CAPTIONS', 'unavailable', 'no_captions'],
  ['LANGUAGE_NOT_AVAILABLE', 'unavailable', 'language_not_available'],
  ['NOT_FOUND', 'unavailable', 'not_found'],
  ['PRIVATE', 'unavailable', 'private'],
  ['MEMBERS_ONLY', 'unavailable', 'members_only'],
  ['AGE_RESTRICTED', 'unavailable', 'age_restricted'],
  ['BLOCKED', 'dependency_failure', 'upstream_failure'],
  ['RATE_LIMITED', 'dependency_failure', 'upstream_failure'],
  ['UPSTREAM_ERROR', 'dependency_failure', 'upstream_failure'],
])('classifies error item %s intentionally, keeping error items free', async (code, outcome, reason) => {
  upstream.mockResolvedValue(Response.json({ data: [{ error: code, retryable: true, message: 'sensitive upstream detail' }], meta: {} }));
  expect(await fetchVakitekTranscript(input)).toMatchObject({ outcome, reason, metadata: { upstreamStatus: 200, billableCredits: null, billingKind: 'unknown' } });
  expectOneNativeCall();
  expect(completion()).toMatchObject({ outcome, reason, requestId: input.requestId, latencyMs: expect.any(Number) });
  const logs = JSON.stringify(vi.mocked(console.info).mock.calls);
  expect(logs).not.toContain('sensitive upstream detail');
});

it.each([
  [401, { error: 'UNAUTHORIZED' }],
  [429, { error: 'RATE_LIMITED' }],
  [502, { error: { code: 'UPSTREAM_ERROR', message: 'sensitive upstream detail' } }],
  [500, { error: 'internal-error' }],
])('classifies HTTP %s as dependency_failure without reading billing', async (status, body) => {
  upstream.mockResolvedValue(Response.json(body, { status }));
  const result = await fetchVakitekTranscript(input);
  expect(result).toMatchObject({ outcome: 'dependency_failure', reason: 'upstream_failure', metadata: { upstreamStatus: status, billableCredits: null } });
  expectOneNativeCall();
  expect(JSON.stringify(vi.mocked(console.info).mock.calls)).not.toContain('secret-test-key');
});

it.each([null, {}, { data: [] }, { data: 'plain text' }, { data: [null] }, { data: [{}] },
  { data: [{ transcript: 'plain text' }] },
  { data: [{ transcript: [{ text: 'hello', start: '0', dur: 1 }] }] },
  { data: [{ transcript: [{ text: 'hello', start: -1, dur: 1 }] }] },
  { data: [{ transcript: [{ text: 'hello', start: 0 }] }] },
  { data: [{ transcript: [{ text: '   ', start: 0, dur: 1 }] }] },
])('rejects malformed content without retry: %j', async body => {
  upstream.mockResolvedValue(Response.json(body));
  expect(await fetchVakitekTranscript(input)).toMatchObject({ outcome: 'dependency_failure', reason: 'malformed_content' });
  expectOneNativeCall();
});

it('treats an empty transcript array as unavailable while keeping billed metadata visible', async () => {
  upstream.mockResolvedValue(Response.json({ data: [{ transcript: [] }], billing: { events: { transcript: 1 } } }));
  expect(await fetchVakitekTranscript(input)).toMatchObject({ outcome: 'unavailable', reason: 'empty_content', metadata: { billableCredits: 1, billingKind: 'reported' } });
  expectOneNativeCall();
});

it('handles invalid JSON for HTTP 200', async () => {
  upstream.mockResolvedValue(new Response('not json secret', { status: 200 }));
  expect(await fetchVakitekTranscript(input)).toMatchObject({ outcome: 'dependency_failure', reason: 'malformed_content' });
  expectOneNativeCall();
});

it.each([null, '', '0', 'not-a-number'])('leaves billing unknown without inferring zero for %j', async value => {
  const billing = value === null ? {} : { events: { transcript: value === '0' ? 0 : value } };
  upstream.mockResolvedValue(Response.json({ data: nativeBody.data, billing: value === null ? undefined : billing }));
  const known = value === '0';
  expect(await fetchVakitekTranscript(input)).toMatchObject({ metadata: {
    billableCredits: known ? 0 : null, billingKind: known ? 'reported' : 'unknown',
  } });
  expectOneNativeCall();
});

it.each(['headers', 'body'])('bounds waiting for stalled %s, aborts locally, and never resubmits', async phase => {
  vi.useFakeTimers();
  upstream.mockImplementation(() => phase === 'headers' ? new Promise(() => {}) : Promise.resolve({
    status: 200, headers: new Headers(), json: () => new Promise(() => {}),
  }));
  const pending = fetchVakitekTranscript(input);
  await vi.advanceTimersByTimeAsync(VAKITEK_TIMEOUT_MS);
  expect(await pending).toMatchObject({ outcome: 'unknown_upstream_acceptance', reason: 'timeout', metadata: {
    upstreamStatus: phase === 'headers' ? null : 200, latencyMs: VAKITEK_TIMEOUT_MS,
  } });
  expect(upstream.mock.calls[0][1].signal.aborted).toBe(true);
  expectOneNativeCall();
  expect(vi.getTimerCount()).toBe(0);
});

it('treats transport failures as unknown acceptance and redacts thrown details', async () => {
  upstream.mockRejectedValue(new Error('secret-test-key cookie=secret'));
  expect(await fetchVakitekTranscript(input)).toMatchObject({ outcome: 'unknown_upstream_acceptance', reason: 'network_failure' });
  expectOneNativeCall();
  expect(JSON.stringify(vi.mocked(console.info).mock.calls)).not.toContain('secret');
});

it('cancels in-flight waiting without starting another request', async () => {
  const controller = new AbortController();
  upstream.mockImplementation(() => new Promise(() => {}));
  const pending = fetchVakitekTranscript({ ...input, signal: controller.signal });
  controller.abort();
  expect(await pending).toMatchObject({ outcome: 'unknown_upstream_acceptance', reason: 'cancelled' });
  expectOneNativeCall();
});

it('does not submit already-cancelled requests', async () => {
  expect(await fetchVakitekTranscript({ ...input, signal: AbortSignal.abort() })).toMatchObject({ outcome: 'dependency_failure', reason: 'cancelled' });
  expect(upstream).not.toHaveBeenCalled();
});
